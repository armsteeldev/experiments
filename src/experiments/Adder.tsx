function DetailPanel({ gate, signal, evaluation, resolved, circuit, onClose }: {
  gate: AdderGate | null; signal: string | null; evaluation: ReturnType<typeof evaluateAdder>; resolved: Set<string>; circuit: ReturnType<typeof createAdderCircuit>; onClose: () => void
}) {
  if (!gate && !signal) return null
  if (gate) {
    const formula = gateFormula(gate, evaluation.values, resolved)
    return <aside className="adder-inspector exp-hud" aria-live="polite" aria-label="Selected gate details">
      <button className="adder-inspector-close" aria-label="Close gate details" onClick={onClose}>×</button>
      <span className="adder-inspector-kicker">{circuit.architecture === 'ripple' ? gate.bit === 0 ? 'HALF ADDER' : 'FULL ADDER' : `CARRY-LOOKAHEAD · STAGE ${gate.stage || 'INPUT'}`} · BIT {gate.bit}</span>
      <div className="adder-inspector-title"><span className={`gate-chip gate-chip-${gate.kind.toLowerCase()}`}>{gate.kind}</span><strong>{roleTitle(gate)}</strong><b>{formula.output}</b></div>
      <div className="adder-inspector-equation"><span>{formula.args.map((arg) => `${humanSignalName(arg.signal, circuit)} ${arg.value === null ? '·' : Number(arg.value)}`).join('   ')}</span><i>{formula.expression} = {formula.output}</i></div>
      <p>{gateExplanation(gate)}</p>
    </aside>
  }
  const sourceGate = circuit.gates.find((item) => item.id === signal)
  const value = signal ? resolved.has(signal) ? Number(evaluation.values[signal]) : '·' : '·'
  return <aside className="adder-inspector exp-hud" aria-live="polite" aria-label="Selected signal details">
    <button className="adder-inspector-close" aria-label="Close signal details" onClick={onClose}>×</button>
    <span className="adder-inspector-kicker">SIGNAL PROBE · {sourceGate ? roleTitle(sourceGate).toUpperCase() : 'INPUT / CARRY'}</span>
    <div className="adder-inspector-title"><span className="gate-chip gate-chip-signal">{signal ? humanSignalName(signal, circuit) : '—'}</span><strong>{sourceGate ? `${sourceGate.kind} output` : 'Constant or input'}</strong><b>{value}</b></div>
    <div className="adder-inspector-equation"><span>{signal && sourceGate ? sourceGate.inputs.map((item) => humanSignalName(item, circuit)).join('   ') : 'Trace the selected conductor'}</span><i>{resolved.has(signal || '') ? 'RESOLVED' : 'AWAITING PROPAGATION'}</i></div>
    <p>{sourceGate ? gateExplanation(sourceGate) : signal === 'ZERO' ? 'The first carry-in is tied low. No incoming carry enters the least significant bit.' : 'This conductor is one node in the actual gate-level arithmetic graph.'}</p>
  </aside>
}

export default function Adder({ paused, controlsVisible, onCloseControls }: ExperimentControls) {
  const [width, setWidth] = useState(8)
  const [architecture, setArchitecture] = useState<AdderArchitecture>('ripple')
  const [aText, setAText] = useState('137')
  const [bText, setBText] = useState('86')
  const [cursor, setCursor] = useState(0)
  const [runStarted, setRunStarted] = useState(false)
  const [playing, setPlaying] = useState(false)
  const [speed, setSpeed] = useState(1)
  const [selection, setSelection] = useState<{ gate: AdderGate } | { signal: string } | null>(null)
  const [camera, setCamera] = useState<Camera>(() => ({ x: 0, y: 55, width: 104 + 8 * ripplePitch + 180, height: 680 }))
  const [reducedMotion, setReducedMotion] = useState(() => window.matchMedia('(prefers-reduced-motion: reduce)').matches)
  const [pageVisible, setPageVisible] = useState(() => !document.hidden)
  const svgRef = useRef<SVGSVGElement>(null)
  const dragRef = useRef<{ id: number; x: number; y: number; cameraX: number; cameraY: number } | null>(null)

  const circuit = useMemo(() => createAdderCircuit(width, architecture), [width, architecture])
  const trace = useMemo(() => createAdderTrace(circuit), [circuit])
  const max = maxForWidth(width)
  const a = Number(aText)
  const b = Number(bText)
  const validA = Number.isInteger(a) && a >= 0 && a <= max
  const validB = Number.isInteger(b) && b >= 0 && b <= max
  const validInputs = validA && validB
  const safeA = validA ? a : 0
  const safeB = validB ? b : 0
  const evaluation = useMemo(() => evaluateAdder(circuit, safeA, safeB), [circuit, safeA, safeB])
  const layout = useMemo(() => {
    const firstGate = circuit.gates[0]
    const dimensions = makeLayout(width, architecture, firstGate)
    return { width: dimensions.worldWidth, height: dimensions.worldHeight }
  }, [width, architecture, circuit])
  const safeCursor = clampTraceIndex(cursor, trace.length)
  const visibleGates = useMemo(() => new Set(circuit.gates.slice(0, safeCursor).map((gate) => gate.id)), [circuit.gates, safeCursor])
  const resolved = useMemo(() => runStarted ? resolvedSignalsAt(circuit, safeCursor) : new Set<string>(['ZERO']), [circuit, safeCursor, runStarted])
  const resolvedWires = useMemo(() => runStarted ? resolvedWiresAt(circuit, safeCursor) : new Set<string>(), [circuit, safeCursor, runStarted])
  const activeGate = safeCursor > 0 ? circuit.gates[safeCursor - 1] : undefined
  const complete = runStarted && safeCursor === trace.length - 1
  const selectedGate = selection && 'gate' in selection ? selection.gate : null
  const selectedSignal = selection && 'signal' in selection ? selection.signal : null
  const focused = useMemo(() => {
    const focus = selectedGate?.id || selectedSignal
    return focus ? logicPathTo(circuit, focus) : null
  }, [circuit, selectedGate, selectedSignal])

  const resetTrace = useCallback((clearSelection = false) => {
    setPlaying(false)
    setRunStarted(false)
    setCursor(0)
    if (clearSelection) setSelection(null)
  }, [])

  const fitCircuit = useCallback(() => setCamera({ x: 0, y: 0, width: layout.width, height: layout.height }), [layout])
  const fitInitialView = useCallback(() => {
    const rect = svgRef.current?.getBoundingClientRect()
    if (!rect || !rect.width || !rect.height) { setCamera({ x: 0, y: 55, width: layout.width, height: layout.height }); return }
    if (rect.width <= 520) {
      const height = layout.height + 80
      const width = height * rect.width / rect.height
      // Start at the least significant inputs on narrow screens so the first
      // visible stage has a legible origin; panning reveals the remaining bus.
      setCamera({ x: 0, y: -30, width, height })
    } else setCamera({ x: 0, y: 55, width: layout.width, height: layout.height })
  }, [layout])

  useEffect(() => {
    fitInitialView()
  }, [fitInitialView])

  useEffect(() => {
    const svg = svgRef.current
    if (!svg) return
    const observer = new ResizeObserver(() => {
      if (!dragRef.current) fitInitialView()
    })
    observer.observe(svg)
    return () => observer.disconnect()
  }, [fitInitialView])

  useEffect(() => {
    const preference = window.matchMedia('(prefers-reduced-motion: reduce)')
    const update = () => setReducedMotion(preference.matches)
    preference.addEventListener('change', update)
    return () => preference.removeEventListener('change', update)
  }, [])

  useEffect(() => {
    const update = () => setPageVisible(!document.hidden)
    document.addEventListener('visibilitychange', update)
    return () => document.removeEventListener('visibilitychange', update)
  }, [])

  useEffect(() => {
    if (!playing || paused || !pageVisible) return
    if (safeCursor >= trace.length - 1) { setPlaying(false); return }
    const timer = window.setTimeout(() => setCursor((index) => Math.min(index + 1, trace.length - 1)), 145 / speed)
    return () => window.clearTimeout(timer)
  }, [playing, paused, pageVisible, safeCursor, speed, trace.length])

  // Open on the real gate trace so the first view already demonstrates the
  // machine. Visitors can pause, step, inspect, or replay it immediately.
  useEffect(() => {
    const timer = window.setTimeout(() => {
      setRunStarted(true)
      setCursor(reducedMotion ? trace.length - 1 : 0)
      setPlaying(!reducedMotion)
    }, 650)
    return () => window.clearTimeout(timer)
  }, [])

  const zoomAt = useCallback((point: Point, factor: number) => {
    setCamera((current) => {
      const nextWidth = Math.max(layout.width * 0.07, Math.min(layout.width * 2.8, current.width / factor))
      const nextHeight = Math.max(layout.height * 0.07, Math.min(layout.height * 2.8, current.height / factor))
      const ratio = current.width / nextWidth
      return { x: point.x - (point.x - current.x) / ratio, y: point.y - (point.y - current.y) / ratio, width: nextWidth, height: nextHeight }
    })
  }, [layout])

  useEffect(() => {
    const svg = svgRef.current
    if (!svg) return
    const onWheel = (event: WheelEvent) => {
      event.preventDefault()
      const matrix = svg.getScreenCTM()
      if (!matrix) return
      const point = svg.createSVGPoint()
      point.x = event.clientX; point.y = event.clientY
      const local = point.matrixTransform(matrix.inverse())
      zoomAt({ x: local.x, y: local.y }, Math.exp(-event.deltaY * 0.0012))
    }
    svg.addEventListener('wheel', onWheel, { passive: false })
    return () => svg.removeEventListener('wheel', onWheel)
  }, [zoomAt, layout])

  const pointerDown = (event: ReactPointerEvent<SVGSVGElement>) => {
    const target = event.target as SVGElement
    if (target.closest('[data-interactive="true"], [data-wire-id]')) return
    if (event.button !== 0 && event.pointerType !== 'touch') return
    const svg = svgRef.current
    if (!svg) return
    svg.setPointerCapture(event.pointerId)
    dragRef.current = { id: event.pointerId, x: event.clientX, y: event.clientY, cameraX: camera.x, cameraY: camera.y }
  }

  const pointerMove = (event: ReactPointerEvent<SVGSVGElement>) => {
    const drag = dragRef.current
    if (!drag || drag.id !== event.pointerId) return
    const rect = svgRef.current?.getBoundingClientRect()
    if (!rect) return
    setCamera((current) => ({
      ...current,
      x: drag.cameraX - (event.clientX - drag.x) * current.width / rect.width,
      y: drag.cameraY - (event.clientY - drag.y) * current.height / rect.height,
    }))
  }

  const pointerUp = (event: ReactPointerEvent<SVGSVGElement>) => {
    if (dragRef.current?.id === event.pointerId) dragRef.current = null
  }

  const chooseWidth = (nextWidth: number) => {
    const nextMax = maxForWidth(nextWidth)
    setWidth(nextWidth)
    if (Number(aText) > nextMax) setAText(String(nextMax))
    if (Number(bText) > nextMax) setBText(String(nextMax))
    resetTrace(true)
  }

  const changeInput = (which: 'a' | 'b', value: string) => {
    if (which === 'a') setAText(value)
    else setBText(value)
    resetTrace()
  }

  const calculate = () => {
    if (!validInputs) return
    setRunStarted(true)
    setCursor(reducedMotion ? trace.length - 1 : 0)
    setPlaying(!reducedMotion)
    setSelection(null)
  }

  const playPause = () => {
    if (playing) { setPlaying(false); return }
    if (safeCursor >= trace.length - 1) setCursor(0)
    setRunStarted(true)
    setPlaying(true)
  }

  const step = (delta: number) => {
    setPlaying(false)
    if (delta > 0) setRunStarted(true)
    setCursor((index) => clampTraceIndex(index + delta, trace.length))
  }

  const restart = () => { setRunStarted(true); setPlaying(false); setCursor(0) }
  const resetAll = () => {
    setAText('137'); setBText('86'); setWidth(8); setArchitecture('ripple')
    resetTrace(true)
  }

  const setSignalSelection = (signal: string) => setSelection({ signal })
  const totalBits = Array.from({ length: width }, (_, bit) => width - 1 - bit)
  const binaryA = validA ? totalBits.map((bit) => ((a >> bit) & 1).toString()).join('') : '—'.repeat(width)
  const binaryB = validB ? totalBits.map((bit) => ((b >> bit) & 1).toString()).join('') : '—'.repeat(width)
  const displayedBinary = evaluation.sumBits.slice().reverse().map((bit, index) => resolved.has(circuit.sumSignals[width - 1 - index]) ? Number(bit) : '·').join('')
  const carryKnown = (bit: number) => resolved.has(circuit.carrySignals[bit])
  const selectedValues = selectedGate ? gateFormula(selectedGate, evaluation.values, resolved) : null

  return <section className="experiment-surface adder-surface" aria-label="The Adder gate-level arithmetic machine">
    <div className="adder-ambient" aria-hidden="true" />
    <header className="adder-console">
      <div className="adder-title-block">
        <span className="adder-kicker"><i /> COMPUTING STUDY · 13</span>
        <h1>THE <em>ADDER</em></h1>
        <p>One sum. Every gate.</p>
      </div>
      <div className="adder-equation">
        <label className="adder-input" aria-label="First number">
          <span>INPUT A</span>
          <input type="number" inputMode="numeric" min="0" max={max} step="1" value={aText} aria-invalid={!validA} title={`Enter a whole number from 0 to ${max}`} onChange={(event) => changeInput('a', event.target.value)} />
          <code>{binaryA.match(/.{1,4}/g)?.join(' ')}</code>
        </label>
        <span className="adder-operator">+</span>
        <label className="adder-input" aria-label="Second number">
          <span>INPUT B</span>
          <input type="number" inputMode="numeric" min="0" max={max} step="1" value={bText} aria-invalid={!validB} title={`Enter a whole number from 0 to ${max}`} onChange={(event) => changeInput('b', event.target.value)} />
          <code>{binaryB.match(/.{1,4}/g)?.join(' ')}</code>
        </label>
        <span className="adder-equals">=</span>
        <div className={`adder-result-readout${complete ? ' result-complete' : ''}`} aria-live="polite">
          <span>OUTPUT · {width} BIT</span>
          <strong>{complete ? evaluation.unsignedResult : '—'}</strong>
          <code>{runStarted ? displayedBinary : '·'.repeat(width)}</code>
          <small>CO {complete ? Number(evaluation.carryOut) : '·'} · OV {complete ? Number(evaluation.signedOverflow) : '·'}</small>
        </div>
        <button className="adder-calculate" onClick={calculate} disabled={!validInputs} aria-label="Calculate and animate the addition"><span>▶</span> CALCULATE</button>
      </div>
      <div className="adder-modes" aria-label="Circuit configuration">
        <label><span>WIDTH</span><select value={width} onChange={(event) => chooseWidth(Number(event.target.value))} aria-label="Adder width"><option value={4}>4 bit</option><option value={8}>8 bit</option><option value={16}>16 bit</option></select></label>
        <span className="adder-mode-divider" />
        <div className="adder-architecture" role="group" aria-label="Adder architecture">
          <button className={architecture === 'ripple' ? 'mode-active' : ''} onClick={() => { setArchitecture('ripple'); resetTrace(true) }} aria-pressed={architecture === 'ripple'}>Ripple</button>
          <button className={architecture === 'lookahead' ? 'mode-active' : ''} onClick={() => { setArchitecture('lookahead'); resetTrace(true) }} aria-pressed={architecture === 'lookahead'}>Look-ahead</button>
        </div>
      </div>
    </header>

    <div className="adder-circuit-meta">
      <span><i className="meta-input" /> INPUT LINES</span>
      <span><i className="meta-carry" /> CARRY</span>
      <span><i className="meta-output" /> SUM OUTPUT</span>
      <b>{!runStarted ? 'MACHINE IDLE' : complete ? 'ALL OUTPUTS RESOLVED' : `${safeCursor} / ${circuit.gates.length} GATES RESOLVED`}</b>
    </div>

    <svg
      ref={svgRef}
      className="adder-circuit"
      viewBox={`${camera.x} ${camera.y} ${camera.width} ${camera.height}`}
      preserveAspectRatio="xMidYMid meet"
      role="application"
      aria-label={`${width}-bit ${architecture === 'ripple' ? 'ripple-carry' : 'Kogge–Stone carry-lookahead'} adder. Drag open space to pan; use the wheel or zoom controls to inspect gates.`}
      onPointerDown={pointerDown}
      onPointerMove={pointerMove}
      onPointerUp={pointerUp}
      onPointerCancel={pointerUp}
    >
      <defs>
        <pattern id="adder-grid" width="28" height="28" patternUnits="userSpaceOnUse"><circle cx="1" cy="1" r=".7" fill="#92aab0" opacity=".18" /></pattern>
        <radialGradient id="adder-light"><stop stopColor="#42665f" stopOpacity=".15" /><stop offset="1" stopColor="#0a1118" stopOpacity="0" /></radialGradient>
        <filter id="adder-dot-glow" x="-200%" y="-200%" width="400%" height="400%"><feGaussianBlur stdDeviation="2.5" result="blur" /><feMerge><feMergeNode in="blur" /><feMergeNode in="SourceGraphic" /></feMerge></filter>
        <linearGradient id="adder-gate-metal" x1="0" y1="0" x2="0" y2="1"><stop stopColor="#1b3036" /><stop offset="1" stopColor="#0b171e" /></linearGradient>
      </defs>
      <rect x={0} y={0} width={layout.width} height={layout.height} fill="#081017" />
      <rect x={0} y={0} width={layout.width} height={layout.height} fill="url(#adder-grid)" />
      <rect x={0} y={0} width={layout.width} height={layout.height} fill="url(#adder-light)" />
      {architecture === 'ripple' ? <g className="adder-stage-backplates">
        {Array.from({ length: width }, (_, bit) => {
          const x = 104 + bit * ripplePitch
          return <g key={bit} className={`adder-stage-plate${activeGate?.bit === bit ? ' stage-current' : ''}`}>
            <rect x={x - 7} y="91" width="154" height="455" rx="5" />
            <text className="stage-index" x={x} y="108">BIT {String(bit).padStart(2, '0')}</text>
            <text className="stage-kind" x={x + 145} y="108" textAnchor="end">{bit === 0 ? 'HALF ADDER' : 'FULL ADDER'}</text>
          </g>
        })}
        <text className="adder-bus-caption" x="37" y="132">A / B</text>
        <text className="adder-bus-caption" x="37" y="606">SUM</text>
      </g> : <g className="adder-stage-backplates">
        {Array.from({ length: width }, (_, bit) => {
          const y = 130 + (width - 1 - bit) * 50
          return <g key={bit} className={`adder-lookahead-row${activeGate?.bit === bit ? ' stage-current' : ''}`}>
            <rect x="18" y={y + 3} width={layout.width - 48} height="44" rx="2" />
            <text x="11" y={y + 2} textAnchor="end">{String(bit).padStart(2, '0')}</text>
          </g>
        })}
        {Array.from({ length: Math.ceil(Math.log2(width)) }, (_, level) => {
          const x = 154 + width * lookaheadPitch + 38 + level * stagePitch
          return <g className="adder-prefix-label" key={level}>
            <line x1={x - 10} y1="96" x2={x + 88} y2="96" />
            <text x={x} y="84">PREFIX · SPAN {2 ** level}</text>
          </g>
        })}
        <text className="adder-bus-caption" x="34" y="74">INPUT BITS</text>
        <text className="adder-bus-caption" x={layout.width - 177} y="74">SUM RESOLUTION</text>
      </g>}

      <g className="adder-wires">
        {circuit.wires.map((wire) => {
          const start = signalPoint(wire.from, width, architecture, circuit)
          const end = wire.output
            ? wire.output === `C${width}` ? carryOutputPoint(width, architecture, circuit) : outputPoint(wire.output, width, architecture, circuit)
            : (() => {
                const gate = circuit.gates.find((item) => item.id === wire.to)!
                const box = makeLayout(width, architecture, gate).box
                return { x: box.x, y: box.y + box.height / 2 + (gate.inputs.length === 2 ? (wire.inputIndex === 0 ? -7 : 7) : 0) }
              })()
          const d = wirePath(start, end, wire, architecture, width, circuit)
          const pathId = `adder-wire-${compactId(wire.id)}`
          const known = resolvedWires.has(wire.id)
          const value = known ? evaluation.values[wire.from] : false
          const selected = !!focused?.wires.has(wire.id)
          const muted = !!focused && !selected
          const pulse = !!activeGate && activeGate.id === wire.from && runStarted
          return <g className={`adder-wire-group${known ? value ? ' wire-one' : ' wire-zero' : ' wire-open'}${selected ? ' wire-focused' : ''}${muted ? ' wire-muted' : ''}`} key={wire.id} data-wire-id={wire.id}>
            <path className="adder-wire-under" d={d} />
            <path id={pathId} className="adder-wire-line" d={d} onClick={(event) => { event.stopPropagation(); setSignalSelection(wire.from) }} />
            {pulse && <circle className="adder-travel-pulse" r="3.1" filter="url(#adder-dot-glow)"><animateMotion key={`${wire.id}-${safeCursor}`} dur={`${Math.max(180, 390 / speed)}ms`} repeatCount="1" fill="remove"><mpath href={`#${pathId}`} /></animateMotion></circle>}
            {wire.output && wire.output.startsWith('S') && architecture === 'ripple' && <circle className="adder-output-stub" cx={end.x + 6} cy={end.y} r="1.4" />}
          </g>
        })}
      </g>

      <g className="adder-input-terminals">
        {circuit.inputSignals.map((signal) => <InputTerminal key={signal} signal={signal} box={makeSourceBox(signal, width, architecture)} value={evaluation.values[signal]} live={resolved.has(signal)} />)}
      </g>

      <g className="adder-gates">
        {circuit.gates.map((gate) => {
          const box = makeLayout(width, architecture, gate).box
          return <GateGlyph key={gate.id} gate={gate} box={box} value={evaluation.values[gate.id]} resolved={visibleGates.has(gate.id)} active={activeGate?.id === gate.id} selected={selectedGate?.id === gate.id} muted={!!focused && !focused.gates.has(gate.id)} onSelect={(item) => setSelection({ gate: item })} />
        })}
      </g>

      <g className="adder-result-terminals">
        {circuit.sumSignals.map((signal, bit) => <ResultTerminal key={signal} signal={signal} label={`S${shortBit(bit)}`} point={outputPoint(signal, width, architecture, circuit)} value={evaluation.values[signal]} known={resolved.has(signal)} selected={selectedSignal === signal} onSelect={setSignalSelection} />)}
        {(() => {
          const signal = circuit.carrySignals[width]
          return <ResultTerminal signal={signal} label={`C${shortBit(width)}`} point={carryOutputPoint(width, architecture, circuit)} value={evaluation.carryOut} known={resolved.has(signal)} selected={selectedSignal === signal} onSelect={setSignalSelection} />
        })()}
      </g>

      {architecture === 'ripple' ? <g className="adder-carry-annotations">
        <text x="33" y="509">C₀</text>
        {Array.from({ length: width + 1 }, (_, bit) => {
          if (bit === 0) return null
          const x = 104 + (bit - 1) * ripplePitch + 157
          return <text key={bit} x={x} y="534">C{shortBit(bit)}</text>
        })}
      </g> : null}
    </svg>

    <div className="adder-carry-rail exp-hud" aria-label="Carry propagation trace">
      <div className="carry-rail-heading"><span>CARRY RAIL</span><small>{architecture === 'ripple' ? 'BIT BY BIT' : 'PREFIX RESULT'}</small></div>
      <div className="carry-rail-bits">
        {circuit.carrySignals.map((signal, bit) => {
          const known = carryKnown(bit)
          const current = activeGate && (activeGate.role === 'carry' && activeGate.bit + 1 === bit || activeGate.role === 'generate' && activeGate.bit === 0 && bit === 1 || activeGate.role === 'prefix-carry' && activeGate.stage === Math.ceil(Math.log2(width)) && activeGate.bit + 1 === bit)
          return <button key={`${signal}-${bit}`} className={`carry-bit${known ? evaluation.carries[bit] ? ' carry-high' : ' carry-low' : ''}${current ? ' carry-current' : ''}`} onClick={() => setSignalSelection(signal)} aria-label={`Inspect carry C${bit}, ${known ? Number(evaluation.carries[bit]) : 'unresolved'}`}>
            <small>C{shortBit(bit)}</small><strong>{known ? Number(evaluation.carries[bit]) : '·'}</strong>
          </button>
        })}
      </div>
    </div>

    <DetailPanel gate={selectedGate} signal={selectedSignal} evaluation={evaluation} resolved={resolved} circuit={circuit} onClose={() => setSelection(null)} />

    <div className="adder-transport exp-hud" aria-label="Calculation playback controls">
      <div className="adder-transport-actions">
        <button onClick={restart} aria-label="Restart calculation from the input lines" title="Restart"><span>↶</span></button>
        <button onClick={() => step(-1)} disabled={!runStarted || safeCursor === 0} aria-label="Step backward one gate" title="Previous gate">‹</button>
        <button className="transport-play" onClick={playPause} aria-label={playing ? 'Pause calculation' : 'Play calculation'} title={playing ? 'Pause' : 'Play'}><span>{playing ? 'Ⅱ' : '▶'}</span></button>
        <button onClick={() => step(1)} disabled={safeCursor >= trace.length - 1} aria-label="Step forward one gate" title="Next gate">›</button>
        <button onClick={() => zoomAt({ x: camera.x + camera.width / 2, y: camera.y + camera.height / 2 }, 1.18)} aria-label="Zoom in" title="Zoom in">＋</button>
        <button onClick={() => zoomAt({ x: camera.x + camera.width / 2, y: camera.y + camera.height / 2 }, 1 / 1.18)} aria-label="Zoom out" title="Zoom out">−</button>
        <button className="transport-fit" onClick={fitCircuit} aria-label="Fit the complete circuit to the viewport" title="Fit circuit">FIT</button>
      </div>
      <div className="adder-progress" aria-label={`${safeCursor} of ${circuit.gates.length} gates resolved`}>
        <span style={{ width: `${safeCursor / Math.max(1, circuit.gates.length) * 100}%` }} />
      </div>
      <div className="adder-transport-readout">
        <span>{activeGate ? `${gateLabel(activeGate)} · ${activeGate.kind}` : runStarted ? 'INPUT LINES SETTLED' : 'READY TO CALCULATE'}</span>
        <label>RATE <select value={speed} onChange={(event) => setSpeed(Number(event.target.value))} aria-label="Playback speed"><option value={0.5}>½×</option><option value={1}>1×</option><option value={2}>2×</option><option value={4}>4×</option></select></label>
        <button className="transport-reset" onClick={resetAll} title="Restore 137 + 86 and clear the trace">RESET</button>
      </div>
    </div>

    <div className="adder-signed-status" aria-live="polite">
      <span>{complete ? `CARRY OUT  ${Number(evaluation.carryOut)}` : 'CARRY OUT  ·'}</span>
      <i />
      <span>{complete ? `SIGNED OVERFLOW  ${Number(evaluation.signedOverflow)}` : 'SIGNED OVERFLOW  ·'}</span>
      {complete && <small>{evaluation.signedA} + {evaluation.signedB} = {evaluation.signedResult} signed</small>}
    </div>

    <div className="adder-motion-note">LOGIC-ORDER PLAYBACK · SIMULATED PROPAGATION DELAY · NOT TRANSISTOR TIMING</div>

    <ControlPanel title="The Adder" note="Gate-level arithmetic" visible={controlsVisible} onClose={onCloseControls}>
      <p className="adder-control-copy">Every value belongs to a node in the circuit. Playback reveals one resolved gate at a time; changing an input rebuilds the trace from the source bits.</p>
      <RangeControl label="Playback rate" value={speed} min={0.5} max={4} step={0.5} onChange={setSpeed} format={(value) => `${value}×`} />
      <ActionRow><button className="small-action" onClick={fitCircuit}>Fit full circuit</button><button className="small-action" onClick={restart}>Restart trace</button></ActionRow>
      <p className="control-note">Ripple carry resolves each slice in sequence. Look-ahead combines propagate and generate pairs over spans of 1, 2, 4 and 8. The speed is illustrative; no transistor or propagation-delay claim is made.</p>
      {selectedValues && <p className="control-note">Selected output expression: {selectedValues.expression} = {selectedValues.output}</p>}
    </ControlPanel>
  </section>
}
