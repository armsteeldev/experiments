const gateWidth = 40
const gateHeight = 28
const ripplePitch = 164
const lookaheadPitch = 50
const stagePitch = 92
const maxForWidth = (width: number) => 2 ** width - 1
const shortBit = (bit: number) => bit.toString().replace(/\d/g, (digit) => '₀₁₂₃₄₅₆₇₈₉'[Number(digit)])
const signalName = (signal: string) => signal === 'ZERO' ? 'C₀ = 0' : signal.replace(/^([A-Z])(\d+)$/, (_, prefix: string, bit: string) => `${prefix}${shortBit(Number(bit))}`)
const compactId = (id: string) => id.replace(/[^a-zA-Z0-9_-]/g, '_')

function gateLabel(gate: AdderGate) {
  if (gate.role === 'propagate') return gate.bit === 0 ? 'S₀ · P₀' : `P${shortBit(gate.bit)}`
  if (gate.role === 'generate') return gate.bit === 0 ? 'C₁ · G₀' : `G${shortBit(gate.bit)}`
  if (gate.role === 'sum') return `S${shortBit(gate.bit)}`
  if (gate.role === 'carry-term') return `T${shortBit(gate.bit)}`
  if (gate.role === 'carry') return `C${shortBit(gate.bit + 1)}`
  if (gate.role === 'prefix-term') return `P${shortBit(gate.bit)} · G${shortBit(Math.max(0, gate.bit - 2 ** (gate.stage - 1)))}`
  const span = 2 ** (gate.stage - 1)
  const low = Math.max(0, gate.bit + 1 - 2 * span)
  return `${gate.role === 'prefix-propagate' ? 'P' : 'G'}${shortBit(gate.bit)}:${shortBit(low)}`
}

function roleTitle(gate: AdderGate) {
  const names: Record<AdderGate['role'], string> = {
    propagate: gate.bit === 0 ? 'Half-adder sum' : 'Propagate',
    generate: gate.bit === 0 ? 'Half-adder carry' : 'Generate',
    sum: 'Sum',
    'carry-term': 'Carry term',
    carry: 'Carry out',
    'prefix-term': 'Prefix carry term',
    'prefix-carry': 'Prefix carry',
    'prefix-propagate': 'Prefix propagate',
  }
  return names[gate.role]
}

function humanSignalName(signal: string, circuit: ReturnType<typeof createAdderCircuit>) {
  if (/^[AB]\d+$/.test(signal) || signal === 'ZERO') return signalName(signal)
  const sumBit = circuit.sumSignals.indexOf(signal)
  if (sumBit >= 0) return `S${shortBit(sumBit)}`
  const carryBit = circuit.carrySignals.indexOf(signal)
  if (carryBit >= 0) return `C${shortBit(carryBit)}`
  const gate = circuit.gates.find((item) => item.id === signal)
  return gate ? gateLabel(gate) : signal
}

function gateExplanation(gate: AdderGate) {
  const bit = shortBit(gate.bit)
  switch (gate.role) {
    case 'propagate': return gate.bit === 0
      ? 'At the least significant bit there is no incoming carry, so XOR is already the output bit.'
      : `P${bit} is high when exactly one input bit is high. A carry-in then passes through this slice.`
    case 'generate': return gate.bit === 0
      ? 'Both input bits are high, so the half adder creates the first carry.'
      : `G${bit} is high only when both input bits are high. This slice creates a carry on its own.`
    case 'sum': return `S${bit} = P${bit} ⊕ C${bit}. The incoming carry toggles the bitwise XOR.`
    case 'carry-term': return `P${bit} ∧ C${bit}: a carry passes through only when this slice propagates it.`
    case 'carry': return `C${shortBit(gate.bit + 1)} = G${bit} ∨ (P${bit} ∧ C${bit}). Either a new carry is generated or an incoming one passes through.`
    case 'prefix-term': return 'This AND gate asks whether the upper group propagates a carry generated by the lower group.'
    case 'prefix-carry': return 'The parallel prefix combines two adjacent groups: either the upper group generates a carry, or it passes one from below.'
    case 'prefix-propagate': return 'Both groups must propagate for their combined group to pass a carry through.'
  }
}

function gateFormula(gate: AdderGate, values: Record<string, boolean>, resolved: Set<string>) {
  const args = gate.inputs.map((signal) => ({ signal, value: resolved.has(signal) ? values[signal] : null }))
  const left = args[0]?.value === null || args[0]?.value === undefined ? '·' : Number(args[0].value)
  const right = args[1]?.value === null || args[1]?.value === undefined ? '·' : Number(args[1].value)
  const symbol: Record<GateKind, string> = { AND: '∧', OR: '∨', XOR: '⊕', NOT: '¬' }
  const expression = gate.kind === 'NOT' ? `${symbol[gate.kind]}${left}` : `${left} ${symbol[gate.kind]} ${right}`
  const output = resolved.has(gate.id) ? Number(values[gate.id]) : '·'
  return { args, expression, output }
}

function makeLayout(width: number, architecture: AdderArchitecture, gate: AdderGate) {
  if (architecture === 'ripple') {
    const cellX = 104 + gate.bit * ripplePitch
    const rows: Record<AdderGate['role'], number> = {
      propagate: 194, generate: 376, sum: 276, 'carry-term': 452, carry: 488,
      'prefix-term': 0, 'prefix-carry': 0, 'prefix-propagate': 0,
    }
    const x = cellX + (gate.role === 'propagate' || gate.role === 'generate' ? 36 : gate.role === 'sum' || gate.role === 'carry-term' ? 80 : 122)
    return { box: { x, y: rows[gate.role], width: gate.role === 'carry' ? 38 : gateWidth, height: gateHeight }, worldWidth: 104 + width * ripplePitch + 180, worldHeight: 680, cellX }
  }

  const levels = Math.ceil(Math.log2(width))
  const baseStart = 154
  const prefixStart = baseStart + width * lookaheadPitch + 38
  const stage = gate.stage
  const sumStart = prefixStart + levels * stagePitch + 18
  const cellX = baseStart + gate.bit * lookaheadPitch
  const row = 130 + (width - 1 - gate.bit) * 50
  let x = cellX
  let y = row - gateHeight / 2
  if (gate.stage === 0) {
    x = baseStart + gate.bit * lookaheadPitch
    y = row + (gate.role === 'propagate' ? -18 : 12)
  } else if (gate.role === 'sum') {
    x = sumStart + gate.bit * lookaheadPitch
    y = row - gateHeight / 2
  } else {
    const stageX = prefixStart + (stage - 1) * stagePitch
    x = stageX + (gate.role === 'prefix-carry' ? 44 : 0)
    y = row + (gate.role === 'prefix-propagate' ? -18 : 12)
  }
  return {
    box: { x, y, width: gateWidth, height: gateHeight },
    worldWidth: sumStart + width * lookaheadPitch + 140,
    worldHeight: 260 + width * 50,
    cellX,
  }
}

function makeSourceBox(signal: string, width: number, architecture: AdderArchitecture): Box {
  const bit = Number(signal.slice(1))
  if (architecture === 'ripple') {
    const x = 104 + bit * ripplePitch
    return { x, y: signal[0] === 'A' ? 116 : 305, width: 32, height: 27 }
  }
  const row = 130 + (width - 1 - bit) * 50
  const x = 34 + bit * lookaheadPitch
  return { x, y: row + (signal[0] === 'A' ? -31 : 7), width: 32, height: 18 }
}

function outputPoint(signal: string, width: number, architecture: AdderArchitecture, circuit: ReturnType<typeof createAdderCircuit>): Point {
  const namedBit = /^S(\d+)$/.exec(signal)
  const bit = namedBit ? Number(namedBit[1]) : circuit.sumSignals.indexOf(signal)
  if (architecture === 'ripple') {
    const cellX = 104 + bit * ripplePitch
    return { x: cellX + 153, y: 600 }
  }
  const levels = Math.ceil(Math.log2(width))
  const sumStart = 154 + width * lookaheadPitch + 38 + levels * stagePitch + 18
  const gate = circuit.gates.find((item) => item.id === circuit.sumSignals[bit])
  const x = gate ? makeLayout(width, architecture, gate).box.x + gateWidth : sumStart + bit * lookaheadPitch + gateWidth * 0.5
  const y = 130 + (width - 1 - bit) * 50 + (gate ? 0 : -18)
  return { x: x + 5, y }
}

function carryOutputPoint(width: number, architecture: AdderArchitecture, circuit: ReturnType<typeof createAdderCircuit>): Point {
  const signal = circuit.carrySignals[width]
  const gate = circuit.gates.find((item) => item.id === signal)
  if (architecture === 'ripple') return { x: 104 + width * ripplePitch + 115, y: 510 }
  if (!gate) return { x: 154 + width * 50 + 70, y: 92 }
  const levels = Math.ceil(Math.log2(width))
  const sumStart = 154 + width * lookaheadPitch + 38 + levels * stagePitch + 18
  return { x: sumStart + width * lookaheadPitch + 72, y: 92 }
}

function wirePath(start: Point, end: Point, wire: AdderWire, architecture: AdderArchitecture, width: number, circuit: ReturnType<typeof createAdderCircuit>) {
  if (architecture === 'ripple' && wire.output && wire.output.startsWith('S')) {
    const bit = Number(wire.output.slice(1))
    const railX = 104 + bit * ripplePitch + 157
    return `M${start.x} ${start.y} C${railX - 7} ${start.y} ${railX} ${start.y + 10} ${railX} ${start.y + 18} L${railX} ${end.y - 14} Q${railX} ${end.y} ${railX - 14} ${end.y} L${end.x} ${end.y}`
  }
  if (wire.output === `C${width}` && architecture === 'ripple') {
    return `M${start.x} ${start.y} C${start.x + 40} ${start.y} ${end.x - 40} ${end.y} ${end.x} ${end.y}`
  }
  if (wire.output === `C${width}` && architecture === 'lookahead') {
    const crest = Math.min(start.y, end.y) - 38
    return `M${start.x} ${start.y} C${start.x + 55} ${crest} ${end.x - 55} ${crest} ${end.x} ${end.y}`
  }
  if (architecture === 'ripple' && !wire.output) {
    const target = circuit.gates.find((gate) => gate.id === wire.to)!
    const targetBox = makeLayout(width, architecture, target).box
    const inputY = targetBox.y + targetBox.height / 2 + (target.inputs.length === 2 ? (wire.inputIndex === 0 ? -7 : 7) : 0)
    const endX = targetBox.x
    const dx = Math.max(7, endX - start.x)
    const lane = wire.inputIndex ? 0.57 : 0.43
    const midX = start.x + dx * lane
    return `M${start.x} ${start.y} H${midX} Q${midX + 6} ${start.y} ${midX + 6} ${start.y + Math.sign(inputY - start.y) * Math.min(12, Math.abs(inputY - start.y) / 2)} V${inputY} Q${midX + 6} ${inputY} ${midX + 14} ${inputY} H${endX}`
  }
  const target = circuit.gates.find((gate) => gate.id === wire.to)
  if (target) {
    const targetBox = makeLayout(width, architecture, target).box
    const inputY = targetBox.y + targetBox.height / 2 + (target.inputs.length === 2 ? (wire.inputIndex === 0 ? -7 : 7) : 0)
    const dx = Math.max(8, targetBox.x - start.x)
    const bend = start.x + dx * (wire.inputIndex ? 0.6 : 0.42)
    return `M${start.x} ${start.y} C${bend} ${start.y} ${bend} ${inputY} ${targetBox.x} ${inputY}`
  }
  if (wire.output) {
    const c = circuit.carrySignals[width]
    if (wire.from === c) return `M${start.x} ${start.y} C${start.x + 32} ${start.y} ${end.x - 32} ${end.y} ${end.x} ${end.y}`
  }
  return `M${start.x} ${start.y} C${start.x + Math.max(14, (end.x - start.x) * 0.45)} ${start.y} ${end.x - Math.max(14, (end.x - start.x) * 0.4)} ${end.y} ${end.x} ${end.y}`
}

function signalPoint(signal: string, width: number, architecture: AdderArchitecture, circuit: ReturnType<typeof createAdderCircuit>): Point {
  if (signal === 'ZERO') return { x: 72, y: 468 }
  if (signal.startsWith('A') || signal.startsWith('B')) {
    const box = makeSourceBox(signal, width, architecture)
    return { x: box.x + box.width, y: box.y + box.height / 2 }
  }
  const gate = circuit.gates.find((item) => item.id === signal)
  if (!gate) return { x: 0, y: 0 }
  const box = makeLayout(width, architecture, gate).box
  return { x: box.x + box.width, y: box.y + box.height / 2 }
}

function gateShape(kind: GateKind) {
  if (kind === 'AND') return `M1 2 H18 A13 12 0 0 1 18 26 H1 Z`
  if (kind === 'OR') return `M1 2 Q8 14 1 26 Q18 26 39 14 Q18 2 1 2 Z`
  if (kind === 'XOR') return `M-3 2 Q4 14 -3 26 M1 2 Q8 14 1 26 Q18 26 39 14 Q18 2 1 2 Z`
  return `M2 2 L31 14 L2 26 Z`
}

function GateGlyph({ gate, box, value, resolved, active, selected, muted, onSelect }: {
  gate: AdderGate; box: Box; value: boolean; resolved: boolean; active: boolean; selected: boolean; muted: boolean; onSelect: (gate: AdderGate) => void
}) {
  return <g
    className={`adder-gate gate-${gate.kind.toLowerCase()}${resolved ? ' is-resolved' : ''}${active ? ' is-current' : ''}${selected ? ' is-selected' : ''}${muted ? ' is-muted' : ''}`}
    transform={`translate(${box.x} ${box.y})`}
    data-interactive="true"
    data-gate-id={gate.id}
    tabIndex={0}
    role="button"
    aria-label={`${gate.kind} gate ${gateLabel(gate)}. ${resolved ? `Output ${Number(value)}.` : 'Not resolved yet.'}`}
    onClick={(event) => { event.stopPropagation(); onSelect(gate) }}
    onKeyDown={(event) => { if (event.key === 'Enter' || event.key === ' ') { event.preventDefault(); event.stopPropagation(); onSelect(gate) } }}
  >
    <title>{gate.kind} · {roleTitle(gate)} · {gate.label}</title>
    <rect className="adder-gate-hit" x="-3" y="-3" width={box.width + 11} height={box.height + 23} rx="4" />
    <path className="adder-gate-body" d={gateShape(gate.kind)} fill="url(#adder-gate-metal)" />
    {gate.kind === 'NOT' && <circle className="adder-inversion" cx="35" cy="14" r="3.2" />}
    <circle className="adder-gate-input" cx="0" cy="7" r="1.9" />
    {gate.inputs.length === 2 && <circle className="adder-gate-input" cx="0" cy="21" r="1.9" />}
    <circle className="adder-gate-output" cx={gate.kind === 'NOT' ? 39 : box.width} cy="14" r="2.5" />
    <circle className="adder-gate-led" cx={box.width - 1} cy="2" r="2.6" />
    <text className="adder-gate-readout" x={box.width - 1} y="4.5" textAnchor="middle">{resolved ? Number(value) : '·'}</text>
    <text className="adder-gate-label" x={box.width / 2} y={box.height + 12} textAnchor="middle">{gateLabel(gate)}</text>
  </g>
}

