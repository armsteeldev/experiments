type Point = { x: number; y: number }
type Box = Point & { width: number; height: number }
type GatePlace = { gate: AdderGate; box: Box; level: number }

const maximum = (width: number) => 2 ** width - 1
const bitLabel = (bit: number) => bit.toString().replace(/\d/g, (digit) => '₀₁₂₃₄₅₆₇₈₉'[Number(digit)])
const gateName = (gate: AdderGate) => {
  if (gate.role === 'propagate') return gate.bit === 0 && gate.stage === 0 ? 'SUM · P₀' : `P${bitLabel(gate.bit)}`
  if (gate.role === 'generate') return gate.bit === 0 && gate.stage === 0 ? 'CARRY · G₀' : `G${bitLabel(gate.bit)}`
  if (gate.role === 'sum') return `SUM · S${bitLabel(gate.bit)}`
  if (gate.role === 'carry-term') return `PASS · T${bitLabel(gate.bit)}`
  if (gate.role === 'carry') return `CARRY · C${bitLabel(gate.bit + 1)}`
  if (gate.role === 'prefix-term') return `P${bitLabel(gate.bit)} · G${bitLabel(Math.max(0, gate.bit - 2 ** (gate.stage - 1)))}`
  const span = 2 ** (gate.stage - 1)
  const low = Math.max(0, gate.bit + 1 - 2 * span)
  return `${gate.role === 'prefix-propagate' ? 'P' : 'G'}${bitLabel(gate.bit)}:${bitLabel(low)}`
}

function signalLabel(signal: string, circuit: ReturnType<typeof createAdderCircuit>) {
  if (signal === 'ZERO') return 'C₀ · 0'
  const output = /^S(\d+)$/.exec(signal)
  if (output) return `S${bitLabel(Number(output[1]))}`
  const carry = /^C(\d+)$/.exec(signal)
  if (carry) return `C${bitLabel(Number(carry[1]))}`
  const gate = circuit.gates.find((item) => item.id === signal)
  if (gate) return gateName(gate)
  return signal.replace(/^([AB])(\d+)$/, (_, letter: string, digit: string) => `${letter}${bitLabel(Number(digit))}`)
}

function gateDescription(gate: AdderGate) {
  switch (gate.role) {
    case 'propagate': return gate.bit === 0 && gate.stage === 0
      ? 'The first sum is an XOR: it is 1 when exactly one input is 1.'
      : 'Propagate is 1 when the two input bits differ. If a carry arrives, this slice passes it onward.'
    case 'generate': return 'Generate is 1 only when both input bits are 1. This slice creates a carry on its own.'
    case 'sum': return `This XOR combines P${bitLabel(gate.bit)} with the carry entering bit ${gate.bit}.`
    case 'carry-term': return 'This AND passes an incoming carry only when the input bits differ.'
    case 'carry': return 'The OR joins a new carry with one passed up from the previous bit.'
    case 'prefix-term': return 'This AND asks whether the upper group passes a carry generated by the lower group.'
    case 'prefix-carry': return 'This OR combines a group carry with a carry passed through the group above it.'
    case 'prefix-propagate': return 'Both groups must pass a carry for their combined group to pass one through.'
  }
}

function gateFormula(gate: AdderGate, values: Record<string, boolean>, resolved: Set<string>) {
  const op = gate.kind === 'AND' ? '∧' : gate.kind === 'OR' ? '∨' : '⊕'
  const inputs = gate.inputs.map((signal) => resolved.has(signal) ? Number(values[signal]) : '·')
  const output = resolved.has(gate.id) ? Number(values[gate.id]) : '·'
  return `${inputs.join(` ${op} `)} = ${output}`
}

function glyph(kind: AdderGate['kind']) {
  if (kind === 'AND') return '∧'
  if (kind === 'OR') return '≥1'
  if (kind === 'NOT') return '¬'
  return '⊕'
}

function GateModule({ gate, box, value, resolved, active, selected, onSelect }: {
  gate: AdderGate; box: Box; value: boolean; resolved: boolean; active: boolean; selected: boolean; onSelect: (gate: AdderGate) => void
}) {
  return <g
    className={`adder-module gate-${gate.kind.toLowerCase()}${resolved ? value ? ' module-one' : ' module-zero' : ''}${active ? ' module-active' : ''}${selected ? ' module-selected' : ''}`}
    transform={`translate(${box.x} ${box.y})`}
    role="button"
    tabIndex={0}
    aria-label={`${gate.kind} gate, ${gateName(gate)}, ${resolved ? `output ${Number(value)}` : 'awaiting signal'}`}
    onClick={() => onSelect(gate)}
    onKeyDown={(event) => { if (event.key === 'Enter' || event.key === ' ') { event.preventDefault(); onSelect(gate) } }}
  >
    <rect className="module-shell" width={box.width} height={box.height} rx="10" />
    <path className="module-topline" d={`M10 1 H${box.width - 10}`} />
    <text className="module-kind" x="12" y="19">{gate.kind} GATE</text>
    <text className="module-symbol" x={box.width / 2} y={box.height * 0.69} textAnchor="middle">{glyph(gate.kind)}</text>
    <circle className="module-input" cx="1" cy={box.height * 0.34} r="4" />
    {gate.inputs.length > 1 && <circle className="module-input" cx="1" cy={box.height * 0.72} r="4" />}
    <circle className="module-output" cx={box.width - 1} cy={box.height / 2} r="4" />
    <circle className="module-led" cx={box.width - 15} cy="15" r="4" />
    <text className="module-value" x={box.width - 15} y="29" textAnchor="middle">{resolved ? Number(value) : '·'}</text>
    <text className="module-label" x={box.width / 2} y={box.height + 18} textAnchor="middle">{gateName(gate)}</text>
  </g>
}

